/**
 * Fonction utilitaire pour résoudre une image pertinente pour une prestation selon son nom/catégorie.
 */
export function getServiceImage(serviceNom: string, fallbackUrl?: string): string {
  if (fallbackUrl && fallbackUrl.trim().length > 5) {
    return fallbackUrl;
  }
  const nom = (serviceNom || '').toLowerCase();
  if (nom.includes('tresse') || nom.includes('natte') || nom.includes('braid')) {
    return IMAGE_CATALOG.services.tresses;
  }
  if (nom.includes('lock') || nom.includes('twist') || nom.includes('vanille')) {
    return IMAGE_CATALOG.services.locks;
  }
  if (nom.includes('color') || nom.includes('balayage') || nom.includes('mèche') || nom.includes('blond')) {
    return IMAGE_CATALOG.services.balayageMiel;
  }
  if (nom.includes('botox') || nom.includes('soin') || nom.includes('kératine') || nom.includes('lissage')) {
    return IMAGE_CATALOG.services.soinBotox;
  }
  if (nom.includes('barbe') || nom.includes('rasage') || nom.includes('barber')) {
    return IMAGE_CATALOG.services.tailleBarbe;
  }
  if (nom.includes('homme') || nom.includes('dégradé') || nom.includes('fade')) {
    return IMAGE_CATALOG.services.fadeBarber;
  }
  if (nom.includes('brushing') || nom.includes('coiffage') || nom.includes('wavy')) {
    return IMAGE_CATALOG.services.brushing;
  }
  return IMAGE_CATALOG.services.coupeFemme;
}

/**
 * Fonction utilitaire pour résoudre une image de catégorie de produits.
 */
export function getProductCategoryImage(categoryNom: string, fallbackUrl?: string): string {
  if (fallbackUrl && fallbackUrl.trim().length > 5) {
    return fallbackUrl;
  }
  const nom = (categoryNom || '').toLowerCase();
  if (nom.includes('shampoing') || nom.includes('lavant') || nom.includes('après-shampoing')) {
    return IMAGE_CATALOG.productCategories.shampoings;
  }
  if (nom.includes('huile') || nom.includes('sérum') || nom.includes('elixir')) {
    return IMAGE_CATALOG.productCategories.huilesEtSerums;
  }
  if (nom.includes('masque') || nom.includes('botox') || nom.includes('traitement') || nom.includes('soin')) {
    return IMAGE_CATALOG.productCategories.masquesEtSoins;
  }
  if (nom.includes('barbe') || nom.includes('rasage') || nom.includes('homme')) {
    return IMAGE_CATALOG.productCategories.soinsBarbe;
  }
  if (nom.includes('cire') || nom.includes('spray') || nom.includes('gel') || nom.includes('coiffant')) {
    return IMAGE_CATALOG.productCategories.coiffantsEtCires;
  }
  return IMAGE_CATALOG.productCategories.defaultCategory;
}

/**
 * Fonction utilitaire pour résoudre une image de produit.
 */
export function getProductImage(produitNom: string, fallbackUrl?: string): string {
  if (fallbackUrl && fallbackUrl.trim().length > 5) {
    return fallbackUrl;
  }
  const nom = (produitNom || '').toLowerCase();
  if (nom.includes('shampoing')) return IMAGE_CATALOG.produits.shampoingArgan;
  if (nom.includes('sérum') || nom.includes('huile')) return IMAGE_CATALOG.produits.serumBrillance;
  if (nom.includes('masque')) return IMAGE_CATALOG.produits.masqueKeratine;
  if (nom.includes('barbe')) return IMAGE_CATALOG.produits.huileBarbe;
  if (nom.includes('cire') || nom.includes('gel')) return IMAGE_CATALOG.produits.cireModelante;
  if (nom.includes('spray') || nom.includes('protecteur')) return IMAGE_CATALOG.produits.sprayThermo;
  return IMAGE_CATALOG.produits.defaultProduit;
}

/**
 * Fonction utilitaire pour résoudre une image de variante de prestation (textures, longueurs, styles).
 */
export function getVarianteImage(varianteNom: string, fallbackUrl?: string): string {
  if (fallbackUrl && fallbackUrl.trim().length > 5) {
    return fallbackUrl;
  }
  const nom = (varianteNom || '').toLowerCase();
  if (nom.includes('court') || nom.includes('carré') || nom.includes('bob')) {
    return IMAGE_CATALOG.variantes.court;
  }
  if (nom.includes('mi-long') || nom.includes('moyen') || nom.includes('épaules')) {
    return IMAGE_CATALOG.variantes.miLong;
  }
  if (nom.includes('long') || nom.includes('taille') || nom.includes('extra')) {
    return IMAGE_CATALOG.variantes.long;
  }
  if (nom.includes('afro') || nom.includes('crépu') || nom.includes('frisé') || nom.includes('bouclé') || nom.includes('tresse') || nom.includes('natte')) {
    return IMAGE_CATALOG.variantes.afroTextured;
  }
  if (nom.includes('barbe') || nom.includes('contour') || nom.includes('rasage')) {
    return IMAGE_CATALOG.variantes.barbeSoin;
  }
  return IMAGE_CATALOG.variantes.defaultVariante;
}
